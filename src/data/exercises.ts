function fromRow(r: GuideRow, mob = false): Exercise {
  const [
    id,
    name,
    pattern,
    primary,
    secondary,
    equipment,
    steps,
    cues,
    mistakes,
    safety,
    alternatives = '',
    type = mob ? 'bodyweight' : 'resistance',
    loadMode = 'total',
    sides = 1,
    category = mob ? 'mobility' : 'compound',
  ] = r;
  return {
    id,
    name,
    pattern,
    primary,
    secondary: secondary.split(', '),
    equipment,
    type,
    loadMode,
    sides,
    category,
    diagram: pattern,
    steps: steps.split('|'),
    cues: cues.split('|'),
    mistakes: mistakes.split('|'),
    safety,
    alternatives: alternatives ? alternatives.split(',') : [],
    custom: false,
    archived: false,
  };
}
export const originalExercises: Exercise[] = [
  ...rows.map((r) => fromRow(r)),
  ...mobility.map((r) => fromRow(r, true)),
];
export const guideAliases: Record<string, string> = {
  'Hip switches': 'hip-switch',
  'Thoracic rotations': 'open-book',
  Calves: 'calf-stretch',
  Chest: 'chest-stretch',
  Hamstrings: 'hamstring-stretch',
  'Hip flexors': 'hip-stretch',
};
export function findGuide(label: string, exercises = originalExercises) {
  const base = label.split(' — ')[0];
  return exercises.find(
    (e) =>
      e.id === guideAliases[base] ||
      e.name.toLowerCase() === base.toLowerCase() ||
      e.name.toLowerCase().replace(/s$/, '') === base.toLowerCase().replace(/s$/, ''),
  );
}
